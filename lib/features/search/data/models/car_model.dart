
class Car {
  final String id;
  final String name;
  final String type;
  final String imageUrl;
  final int passengers;
  final int bags;
  final double price;

  Car({
    required this.id,
    required this.name,
    required this.type,
    required this.imageUrl,
    required this.passengers,
    required this.bags,
    required this.price,
  });
}